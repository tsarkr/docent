"""RAGAS evaluation for the Docent benchmark output.

The input file is generated by ``eval_rag_comparison.py`` and contains the
question, retrieved contexts, model response, and curated reference facts.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.config import load_secrets, setting


def evaluate_dataset(dataset_path: Path, output_path: Path) -> None:
    """Run RAGAS metrics and write a JSON report.

    Imports are intentionally lazy so the existing benchmark remains usable
    without installing the optional RAGAS evaluation dependencies.
    """
    try:
        from ragas import EvaluationDataset, evaluate
        from ragas.llms import LangchainLLMWrapper
        from ragas.run_config import RunConfig
        from ragas.metrics import Faithfulness

        try:
            from ragas.metrics import LLMContextPrecisionWithReference, LLMContextRecall
        except ImportError:
            from ragas.metrics import ContextPrecision, ContextRecall

            LLMContextPrecisionWithReference = ContextPrecision
            LLMContextRecall = ContextRecall

    except ImportError as exc:
        raise RuntimeError(
            "RAGAS 평가에는 'ragas'와 'langchain-google-genai'가 필요합니다. "
            "requirements.txt를 설치한 뒤 다시 실행하세요."
        ) from exc

    secrets = load_secrets()

    records = json.loads(dataset_path.read_text(encoding="utf-8"))
    if not records:
        raise RuntimeError(f"RAGAS 입력 데이터가 비어 있습니다: {dataset_path}")

    provider = setting("RAGAS_PROVIDER", "ollama", secrets).lower()
    if provider == "ollama":
        from langchain_ollama import ChatOllama, OllamaEmbeddings

        evaluator_llm = LangchainLLMWrapper(
            ChatOllama(
                model=setting("RAGAS_OLLAMA_MODEL", "gemma4:26b", secrets),
                temperature=0,
                format="json",
                num_predict=256,
                keep_alive="10m",
                think=False,
            )
        )
        evaluator_embeddings = OllamaEmbeddings(
            model=setting(
                "RAGAS_OLLAMA_EMBEDDING_MODEL",
                "nomic-embed-text:latest",
                secrets,
            )
        )
    elif provider == "gemini":
        from langchain_google_genai import (
            ChatGoogleGenerativeAI,
            GoogleGenerativeAIEmbeddings,
        )

        api_key = setting("GEMINI_API_KEY", "", secrets)
        if not api_key:
            raise RuntimeError("Gemini RAGAS 평가를 위해 GEMINI_API_KEY가 필요합니다.")
        evaluator_llm = LangchainLLMWrapper(
            ChatGoogleGenerativeAI(
                model=setting(
                    "GEMINI_RAGAS_MODEL",
                    "gemini-flash-lite-latest",
                    secrets,
                ),
                google_api_key=api_key,
                temperature=0,
                candidate_count=1,
            )
        )
        evaluator_embeddings = GoogleGenerativeAIEmbeddings(
            model=setting(
                "GEMINI_EMBEDDING_MODEL",
                "models/gemini-embedding-001",
                secrets,
            ),
            google_api_key=api_key,
        )
    else:
        raise RuntimeError("RAGAS_PROVIDER는 'ollama' 또는 'gemini'여야 합니다.")
    original_agenerate_text = evaluator_llm.agenerate_text

    async def repaired_agenerate_text(*args: Any, **kwargs: Any):
        result = await original_agenerate_text(*args, **kwargs)
        for generations in result.generations:
            for generation in generations:
                generation.text = re.sub(
                    r"\\u(?![0-9a-fA-F]{4})",
                    r"\\\\u",
                    generation.text,
                )
        return result

    evaluator_llm.agenerate_text = repaired_agenerate_text
    # Gemini models reject multi-candidate requests. RAGAS can evaluate with
    # one completion per prompt when the wrapper does not set the provider's n.
    evaluator_llm.bypass_n = True
    faithfulness_metric = Faithfulness()
    context_metrics = [
        LLMContextPrecisionWithReference(),
        LLMContextRecall(),
    ]
    metrics = [
        faithfulness_metric,
        *context_metrics,
    ]
    scores_by_model: dict[str, list[dict[str, Any]]] = {}
    averages_by_model: dict[str, dict[str, float]] = {}
    models = sorted({record.get("model", "unknown") for record in records})
    for model in models:
        model_records = [record for record in records if record.get("model", "unknown") == model]
        run_config = RunConfig(
            timeout=300,
            max_retries=1,
            max_wait=30,
            max_workers=2,
        )
        direct_records = [
            record for record in model_records
            if record.get("evaluation_type", "direct") == "direct"
        ]
        abstention_records = [
            record for record in model_records
            if record.get("evaluation_type") == "abstention"
        ]
        scores = []
        if direct_records:
            direct_result = evaluate(
                dataset=EvaluationDataset.from_list(direct_records),
                metrics=metrics,
                llm=evaluator_llm,
                embeddings=evaluator_embeddings,
                run_config=run_config,
                raise_exceptions=True,
                show_progress=True,
            )
            scores.extend(direct_result.to_pandas().to_dict(orient="records"))
        if abstention_records:
            abstention_result = evaluate(
                dataset=EvaluationDataset.from_list(abstention_records),
                metrics=[faithfulness_metric],
                llm=evaluator_llm,
                embeddings=evaluator_embeddings,
                run_config=run_config,
                raise_exceptions=True,
                show_progress=True,
            )
            scores.extend(abstention_result.to_pandas().to_dict(orient="records"))
        scores_by_model[model] = scores
        summary: dict[str, list[float]] = {}
        for row in scores:
            for key, value in row.items():
                if key in {"user_input", "response", "retrieved_contexts", "reference"}:
                    continue
                if isinstance(value, (int, float)) and math.isfinite(float(value)):
                    summary.setdefault(key, []).append(float(value))
                elif isinstance(value, float):
                    raise RuntimeError(
                        f"RAGAS metric '{key}' returned a non-finite value "
                        f"for model '{model}'. Evaluation was not completed."
                    )
        averages_by_model[model] = {
            key: round(sum(values) / len(values), 4)
            for key, values in summary.items()
            if values
        }

    output_path.write_text(
        json.dumps(
            {"metrics_by_model": averages_by_model, "records_by_model": scores_by_model},
            ensure_ascii=False,
            indent=2,
            default=str,
        ),
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Evaluate Docent responses with RAGAS.")
    parser.add_argument(
        "--input",
        type=Path,
        default=Path(__file__).resolve().parent / "results" / "ragas_dataset.json",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parent / "results" / "ragas_results.json",
    )
    args = parser.parse_args()
    evaluate_dataset(args.input, args.output)
    print(f"RAGAS 결과 저장 완료: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
